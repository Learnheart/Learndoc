#!/usr/bin/env node
// Compiles schemas/*.schema.json into a dependency-free ESM module (lib/generated-validators.mjs),
// so users never need `npm install`. `--check` fails when the committed output is stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemasDir = path.join(root, 'schemas');
const output = path.join(root, 'lib/generated-validators.mjs');

const readSchema = (name) => JSON.parse(fs.readFileSync(path.join(schemasDir, `${name}.schema.json`), 'utf8'));

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  discriminator: true,
  code: { source: true, esm: true },
});
const exportsMap = {};
for (const name of ['config', 'course', 'lesson', 'changeset', 'answer']) {
  const schema = readSchema(name);
  ajv.addSchema(schema);
  exportsMap[name] = schema.$id;
}
// A single lesson block (with id), for validating blocks produced by a changeset.
exportsMap.block = `${exportsMap.lesson}#/$defs/block`;

const banner = '// Generated by scripts/generate-validators.mjs. Do not edit by hand.\n';
const ajvUcs2Import = 'require("ajv/dist/runtime/ucs2length").default';
const inlineUcs2Length = `function ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  while (pos < len) {
    length += 1;
    const value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len
      && (str.charCodeAt(pos) & 0xfc00) === 0xdc00) pos += 1;
  }
  return length;
}`;

let code = standaloneCode(ajv, exportsMap);
if (!code.includes(ajvUcs2Import)) {
  throw new Error('AJV standalone output no longer contains the expected ucs2length helper');
}
code = code.replaceAll(ajvUcs2Import, inlineUcs2Length);
if (code.includes('require(')) {
  throw new Error('AJV standalone output contains an unexpected runtime dependency');
}
const generated = `${banner}${code}\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8').replace(/\r\n?/g, '\n') : '';
  if (current !== generated) {
    console.error('generated validators are stale — run npm run generate:validators');
    process.exit(1);
  }
  console.log('generated validators are up to date');
} else {
  const temporary = `${output}.${process.pid}.tmp`;
  fs.writeFileSync(temporary, generated);
  fs.renameSync(temporary, output);
  console.log(`generated ${path.relative(root, output)}`);
}
