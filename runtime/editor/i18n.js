// t('blocks', 2) → "2 blocks"; plain strings ignore extra arguments.
export function makeT(language) {
  const table = STRINGS[language] ?? STRINGS.en;
  const t = (key, ...args) => {
    const value = table[key] ?? STRINGS.en[key] ?? key;
    return typeof value === 'function' ? value(...args) : value;
  };
  t.known = (key) => key in STRINGS.en;
  t.lang = STRINGS[language] ? language : 'en';
  return t;
}

// Server warnings ({ code, message, blockId? }) shown in the UI language. The server's
// message (English, may name block ids) is only a fallback for codes we do not know.
export const warningText = (w, t) => (t.known(`warn:${w.code}`) ? t(`warn:${w.code}`) : w.message ?? w.code);

// API errors ({ code, message }) with a friendly text for codes we know.
export const errorText = (err, t) => (t.known(`err:${err.code}`) ? t(`err:${err.code}`) : err.message);
