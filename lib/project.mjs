// Project location, JSON loading with parse diagnostics, `.learndoc/` bootstrap and widget lookup.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { diagnostic } from './diagnostics.mjs';
import * as git from './git.mjs';

export const SKILL_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CONFIG_FILE = 'learndoc.json';
export const COURSE_FILE = 'course.json';
export const STATE_DIR = '.learndoc';
const STATE_GITIGNORE = ['server.json', 'server.log', 'changesets/', 'import/', 'refs/'];
// Generated by earlier versions and no longer used: rendered pages (now only html/) and reference chunk
// files (now an index in .learndoc/refs/). Removed when a project is bootstrapped.
const LEGACY_DIRS = [path.join(STATE_DIR, 'build')];

export const lessonFile = (root, id) => path.join(root, 'lessons', `${id}.json`);
export const relativePath = (root, file) => path.relative(root, file).split(path.sep).join('/');

// Every other lesson file that parses; unreadable ones are skipped.
export function otherLessons(root, lessonId) {
  const dir = path.join(root, 'lessons');
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .filter((f) => f.endsWith('.json') && f !== `${lessonId}.json`)
    .sort()
    .flatMap((f) => {
      try {
        return [JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))];
      } catch {
        return [];
      }
    });
}

// Canonical on-disk form of every learndoc JSON file.
export const formatJson = (value) => `${JSON.stringify(value, null, 2)}\n`;

// Nearest ancestor directory (of a file or directory) containing learndoc.json, or null.
export function findProjectRoot(start) {
  let dir = path.resolve(start);
  if (fs.existsSync(dir) && !fs.statSync(dir).isDirectory()) dir = path.dirname(dir);
  for (;;) {
    if (fs.existsSync(path.join(dir, CONFIG_FILE))) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function lineColumn(text, position) {
  const before = text.slice(0, position);
  const line = before.split('\n').length;
  return { line, column: position - before.lastIndexOf('\n') };
}

// -> { value } or { diagnostic } (missing file or invalid JSON, with line/column when known).
export function readJson(file, { root }) {
  const subject = { file: relativePath(root, file) };
  let text;
  try {
    text = fs.readFileSync(file, 'utf8');
  } catch (error) {
    return {
      diagnostic: diagnostic({
        code: 'project/missing-file',
        message: `${subject.file} cannot be read: ${error.code || error.message}`,
        subject,
        supportedFixes: [`create ${subject.file}`],
      }),
    };
  }
  try {
    return { value: JSON.parse(text) };
  } catch (error) {
    const position = Number(/position (\d+)/.exec(error.message)?.[1]);
    const where = Number.isFinite(position) ? lineColumn(text, position) : null;
    return {
      diagnostic: diagnostic({
        code: 'json/parse',
        message: `${subject.file} is not valid JSON${where ? ` (line ${where.line}, column ${where.column})` : ''}: ${error.message}`,
        subject,
        evidence: where ? { ...where, excerpt: text.split('\n')[where.line - 1]?.slice(0, 200) } : undefined,
        supportedFixes: ['fix the JSON syntax at the reported location (escape backslashes as \\\\ in LaTeX)'],
      }),
    };
  }
}

// Creates `.learndoc/` (+ its .gitignore, missing entries appended), removes what earlier versions
// generated, and runs `git init` when the project is not inside a work tree.
// -> { stateCreated, gitInitialized }
export function bootstrapProject(root) {
  const stateDir = path.join(root, STATE_DIR);
  const stateCreated = !fs.existsSync(stateDir);
  fs.mkdirSync(stateDir, { recursive: true });
  const gitignore = path.join(stateDir, '.gitignore');
  const ignored = fs.existsSync(gitignore) ? fs.readFileSync(gitignore, 'utf8') : '';
  const missing = STATE_GITIGNORE.filter((entry) => !ignored.split('\n').includes(entry));
  if (missing.length) fs.writeFileSync(gitignore, `${ignored}${ignored && !ignored.endsWith('\n') ? '\n' : ''}${missing.join('\n')}\n`);
  for (const dir of LEGACY_DIRS) fs.rmSync(path.join(root, dir), { recursive: true, force: true });
  const gitInitialized = !git.isInsideWorkTree(root);
  if (gitInitialized) git.init(root);
  return { stateCreated, gitInitialized };
}

const BUILTIN_WIDGETS_DIR = path.join(SKILL_ROOT, 'runtime', 'widgets');

// Built-in widget names (files in runtime/widgets/ not starting with '_').
export function builtinWidgetNames() {
  return fs.readdirSync(BUILTIN_WIDGETS_DIR)
    .filter((file) => file.endsWith('.js') && !file.startsWith('_'))
    .map((file) => file.slice(0, -'.js'.length))
    .sort();
}

// Built-in widgets take precedence over project widgets of the same name.
// -> { name, file, url, builtIn } or null
export function resolveWidget(root, name) {
  if (name.startsWith('_')) return null;
  const builtIn = path.join(BUILTIN_WIDGETS_DIR, `${name}.js`);
  if (fs.existsSync(builtIn)) {
    return { name, file: builtIn, url: `/static/runtime/widgets/${name}.js`, builtIn: true };
  }
  const local = path.join(root, 'widgets', `${name}.js`);
  if (fs.existsSync(local)) return { name, file: local, url: `/project/widgets/${name}.js`, builtIn: false };
  return null;
}

const widgetModules = new Map();

// -> the widget module's default export, cached until the file changes. Built-in widgets are imported
// by file URL (the skill is an ESM package); project widgets via a data: URL of their source, so a
// project without "type": "module" still loads them as ES modules.
export async function importWidget(widget) {
  const stat = fs.statSync(widget.file);
  const key = `${widget.file}:${stat.mtimeMs}:${stat.size}`;
  if (!widgetModules.has(key)) {
    const url = widget.builtIn
      ? `${pathToFileURL(widget.file).href}?v=${stat.mtimeMs}`
      : `data:text/javascript;base64,${fs.readFileSync(widget.file).toString('base64')}`;
    widgetModules.set(key, import(url).then((mod) => mod.default));
  }
  return widgetModules.get(key);
}
